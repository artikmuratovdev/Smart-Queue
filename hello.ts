import { Hono } from "hono";
import { cors } from "hono/cors";
import { attachDatabasePool } from "@neon/functions";
import { createRealtime, rawSql } from "@neon/realtime/server";
import { parseEnv } from "@neon/env";
import { Pool } from "pg";
import config from "./neon";

const env = parseEnv(config, ["DATABASE_URL"]);
const pool = new Pool({ connectionString: env.postgres.databaseUrl, max: 5 });
attachDatabasePool(pool);
const database = new URL(env.postgres.databaseUrl).pathname.replace(/^\//, "") || "neondb";
const realtimeSecret = process.env.NAVBAT_REALTIME_SECRET;
if (!realtimeSecret) throw new Error("NAVBAT_REALTIME_SECRET is not configured");
const realtime = createRealtime({ secret: realtimeSecret, db: database });
const app = new Hono();
const allowedOrigins = ["http://localhost:3000", "http://127.0.0.1:3000", "http://localhost:3001", "http://127.0.0.1:3001"];
app.use("/api/*", cors({ origin: allowedOrigins, allowMethods: ["GET", "POST", "OPTIONS"], allowHeaders: ["Content-Type"] }));

let schemaReady: Promise<void> | undefined;
function ensureSchema() {
  schemaReady ??= pool.query(`
    CREATE TABLE IF NOT EXISTS queue_tickets (
      id uuid PRIMARY KEY,
      number bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE NOT NULL,
      service text NOT NULL CHECK (service IN ('admission', 'documents', 'consultation')),
      device_id text NOT NULL,
      status text NOT NULL DEFAULT 'waiting' CHECK (status IN ('waiting', 'called', 'done', 'cancelled')),
      created_at timestamptz NOT NULL DEFAULT now()
    );
    CREATE UNIQUE INDEX IF NOT EXISTS queue_one_active_per_device
      ON queue_tickets(device_id) WHERE status IN ('waiting', 'called');
    CREATE UNIQUE INDEX IF NOT EXISTS queue_one_called_ticket
      ON queue_tickets(status) WHERE status = 'called';
  `).then(() => undefined);
  return schemaReady;
}

async function readState() {
  await ensureSchema();
  const { rows } = await pool.query(`SELECT id, number, service, device_id, status, created_at FROM queue_tickets ORDER BY number`);
  const tickets = rows.map((row) => ({
    id: row.id,
    number: Number(row.number),
    service: row.service,
    deviceId: row.device_id,
    status: row.status,
    created: new Date(row.created_at).getTime(),
  }));
  return { tickets, current: tickets.find((ticket) => ticket.status === "called")?.id ?? null, sequence: tickets.length ? Math.max(...tickets.map((ticket) => ticket.number)) + 1 : 1 };
}

async function transaction<T>(work: (client: import("pg").PoolClient) => Promise<T>) {
  await ensureSchema();
  const client = await pool.connect();
  try {
    await client.query("BEGIN");
    await client.query("SELECT pg_advisory_xact_lock(681942)");
    const result = await work(client);
    await client.query("COMMIT");
    return result;
  } catch (error) {
    await client.query("ROLLBACK");
    throw error;
  } finally {
    client.release();
  }
}

app.get("/api/state", async (c) => c.json(await readState()));
app.post("/api/live", async (c) => {
  await ensureSchema();
  const query = rawSql(`SELECT id, number, service, device_id AS "deviceId", status, created_at AS created FROM queue_tickets ORDER BY number`);
  return c.json(await realtime.seal({ query }));
});

app.post("/api/tickets", async (c) => {
  const input = await c.req.json<{ service?: string; deviceId?: string }>();
  if (!["admission", "documents", "consultation"].includes(input.service || "")) return c.json({ error: "Xizmat noto‘g‘ri" }, 400);
  const deviceId = String(input.deviceId || "").trim().slice(0, 100);
  if (!deviceId) return c.json({ error: "Device ID kerak" }, 400);
  try {
    await transaction(async (client) => {
      const existing = await client.query("SELECT id FROM queue_tickets WHERE device_id = $1 AND status IN ('waiting', 'called') LIMIT 1", [deviceId]);
      if (existing.rowCount) throw new Error("Bu qurilmada faol navbat mavjud");
      await client.query("INSERT INTO queue_tickets (id, service, device_id) VALUES ($1, $2, $3)", [crypto.randomUUID(), input.service, deviceId]);
    });
  } catch (error) {
    if (error instanceof Error && (error.message === "Bu qurilmada faol navbat mavjud" || (error as { code?: string }).code === "23505")) return c.json({ error: "Bu qurilmada faol navbat mavjud", state: await readState() }, 409);
    throw error;
  }
  return c.json(await readState(), 201);
});

app.post("/api/call", async (c) => {
  const { service = "all" } = await c.req.json<{ service?: string }>();
  const result = await transaction(async (client) => {
    const next = await client.query("SELECT id FROM queue_tickets WHERE status = 'waiting' AND ($1 = 'all' OR service = $1) ORDER BY number LIMIT 1 FOR UPDATE", [service]);
    if (!next.rowCount) return false;
    await client.query("UPDATE queue_tickets SET status = 'done' WHERE status = 'called'");
    await client.query("UPDATE queue_tickets SET status = 'called' WHERE id = $1", [next.rows[0].id]);
    return true;
  });
  if (!result) return c.json({ error: "Tanlangan xizmatda navbat yo‘q" }, 409);
  return c.json(await readState());
});

